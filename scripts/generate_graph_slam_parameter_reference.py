"""
Write docs/graph-slam-parameters.md from the graph_based_slam config sources.

The parameter names come from the LOAD(member, "name") calls in
graph_based_slam/src/graph_slam_config.cpp; each member's type, default,
section and comment come from graph_based_slam/src/graph_slam_config.hpp.
--check exits 1 when the page on disk differs from what would be written.
"""

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'graph_based_slam/src/graph_slam_config.hpp'
SOURCE = ROOT / 'graph_based_slam/src/graph_slam_config.cpp'
PAGE = ROOT / 'docs/graph-slam-parameters.md'

FIELD = re.compile(
    r'^\s*(?P<type>[\w:<>]+(?:<[^>]*>)?)\s+(?P<member>\w+)\s*(?:\{(?P<default>.*)\})?;\s*$')
LOAD = re.compile(r'LOAD\(\s*(?P<member>\w+)\s*,\s*"(?P<name>[\w.]+)"\s*\)')


def read_members(header_text):
    """Return GraphSlamConfig's members in order: (member, type, default, section, comment)."""
    body = header_text[header_text.index('struct GraphSlamConfig'):]
    body = body[body.index('{') + 1:body.index('\n};')]
    members, section, comment, after_blank = [], '', [], True
    for line in body.splitlines():
        stripped = line.strip()
        if not stripped:
            after_blank, comment = True, []
            continue
        if stripped.startswith('//'):
            text = stripped[2:].strip()
            if after_blank and not comment:
                # A comment right after a blank line opens a section; the
                # struct's first line counts as after a blank line.
                section, after_blank = text.rstrip('.'), False
            else:
                comment.append(text)
            continue
        match = FIELD.match(line)
        if match:
            default = (match.group('default') or '').strip()
            members.append((match.group('member'), match.group('type'), default, section,
                            ' '.join(comment)))
        after_blank, comment = False, []
    return members


def format_default(type_name, default):
    if not default:
        return '""' if type_name == 'std::string' else ''
    if type_name.startswith('std::vector'):
        return '[' + default + ']'
    return default


def render(header_text, source_text):
    names = {m.group('member'): m.group('name') for m in LOAD.finditer(source_text)}
    lines = [
        '# Graph SLAM Parameters',
        '',
        'Every ROS parameter the `graph_based_slam` node declares, with its type and default,',
        'grouped as in `graph_based_slam/src/graph_slam_config.hpp`. `graph_slam_offline_runner`',
        'reads many of the same names (and some of its own); its source lists them. Presets that',
        'set these parameters are in `lidarslam/param/`.',
        '',
        'This page is generated by `scripts/generate_graph_slam_parameter_reference.py` from the',
        'config sources: a description here is the comment above the member in the header. Edit',
        'the header, then run the script; a test fails while the page is out of date.',
        '',
    ]
    current, count = None, 0
    for member, type_name, default, section, comment in read_members(header_text):
        if member not in names:
            continue
        if section != current:
            current = section
            lines += [f'## {section}', '', '| Parameter | Type | Default | Description |',
                      '| --- | --- | --- | --- |']
        value = format_default(type_name, default).replace('|', '\\|')
        lines.append(f'| `{names[member]}` | `{type_name}` | `{value}` | {comment} |'
                     if value else f'| `{names[member]}` | `{type_name}` | | {comment} |')
        count += 1
    missing = sorted(set(names) - {m[0] for m in read_members(header_text)})
    if missing:
        raise SystemExit(f'LOAD names a member the header does not declare: {missing}')
    lines += ['', f'{count} parameters.', '']
    out, previous = [], None
    for line in lines:
        if line.startswith('## ') and previous != '':
            out.append('')
        out.append(line)
        previous = line
    return '\n'.join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the page is out of date')
    args = parser.parse_args(argv)
    text = render(HEADER.read_text(encoding='utf-8'), SOURCE.read_text(encoding='utf-8'))
    if args.check:
        if PAGE.read_text(encoding='utf-8') != text:
            print(f'{PAGE.relative_to(ROOT)} is out of date; run '
                  'scripts/generate_graph_slam_parameter_reference.py', file=sys.stderr)
            return 1
        return 0
    PAGE.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
